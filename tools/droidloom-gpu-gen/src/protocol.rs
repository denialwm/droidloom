//! Shared output: Vulkan types, function-pointer types, opcodes and the
//! fixed part of every record (its frame).

use std::fmt::Write as _;

use crate::model::{Api, Cmd, ParamKind};
use crate::rust::{array_length, constant, declared, ident, scalar_definition, type_name};

/// The frame field type of one parameter.
pub fn frame_type(api: &Api, kind: &ParamKind, param: &crate::registry::Member) -> Option<String> {
    Some(match kind {
        ParamKind::Value | ParamKind::FdIn => type_name(api, &param.ty),
        ParamKind::Array(dim) => format!("[{}; {}]", type_name(api, &param.ty), array_length(dim)),
        ParamKind::Handle | ParamKind::Dispatchable => "u64".into(),
        ParamKind::Created { len: None, .. } => "u64".into(),
        ParamKind::In(..) | ParamKind::Created { .. } | ParamKind::FdOut | ParamKind::Out { .. } => "i64".into(),
        ParamKind::StreamOwner | ParamKind::Allocator => return None,
    })
}

pub fn pfn_signature(api: &Api, cmd: &Cmd) -> String {
    let params: Vec<String> = cmd
        .params
        .iter()
        .map(|p| {
            let mut member = p.member.clone();
            if !member.array.is_empty() {
                // A C array parameter decays to a pointer.
                member.array.clear();
                member.pointer = crate::registry::Pointer::Const;
            }
            format!("{}: {}", ident(&p.member.name), declared(api, &member))
        })
        .collect();
    let ret = if cmd.ret == "void" { String::new() } else { format!(" -> {}", type_name(api, &cmd.ret)) };
    format!("unsafe extern \"system\" fn({}){ret}", params.join(", "))
}

pub fn emit(api: &Api) -> String {
    let mut out = String::new();
    let registry = api.registry;
    writeln!(out, "// @generated by droidloom-gpu-gen from vk.xml {}. Do not edit.", registry.header_version).ok();
    out.push_str("#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, missing_docs, clippy::all, clippy::pedantic)]\n\n");

    out.push_str("/// Vulkan types reachable from the forwarded commands.\npub mod vk {\n    pub use core::ffi::{c_char, c_int, c_void};\n\n");
    let mut constants: Vec<_> = registry.constants.iter().collect();
    constants.sort();
    for (name, (c_ty, value)) in constants {
        let (ty, value) = constant(c_ty, value);
        writeln!(out, "    pub const {name}: {ty} = {value};").ok();
    }
    for name in [
        "VK_SUCCESS",
        "VK_NOT_READY",
        "VK_TIMEOUT",
        "VK_INCOMPLETE",
        "VK_ERROR_OUT_OF_HOST_MEMORY",
        "VK_ERROR_OUT_OF_DEVICE_MEMORY",
        "VK_ERROR_INITIALIZATION_FAILED",
        "VK_ERROR_DEVICE_LOST",
        "VK_ERROR_EXTENSION_NOT_PRESENT",
        "VK_ERROR_INCOMPATIBLE_DRIVER",
    ] {
        writeln!(out, "    pub const {name}: VkResult = {};", registry.values[name]).ok();
    }
    out.push('\n');
    out.push_str("    pub type VkFlags = u32;\n    pub type VkFlags64 = u64;\n");
    for name in &api.scalars {
        if name != "VkFlags" && name != "VkFlags64" {
            writeln!(out, "    pub type {name} = {};", scalar_definition(api, name)).ok();
        }
    }
    for (_, value) in api.chained() {
        writeln!(out, "    pub const {value}: VkStructureType = {};", registry.values[&value]).ok();
    }
    out.push('\n');
    for name in &api.structs {
        let members = registry.struct_members(name).expect("structure");
        let keyword = if registry.is_union(name) { "union" } else { "struct" };
        writeln!(out, "    #[repr(C)]\n    #[derive(Clone, Copy)]\n    pub {keyword} {name} {{").ok();
        for member in members {
            assert!(!member.bitfield, "{name} has bitfields");
            writeln!(out, "        pub {}: {},", ident(&member.name), declared(api, member)).ok();
        }
        out.push_str("    }\n");
    }
    out.push('\n');
    for cmd in &api.commands {
        writeln!(out, "    pub type PFN_{} = {};", cmd.name, pfn_signature(api, cmd)).ok();
    }
    out.push_str("}\n\n");

    out.push_str("/// Record opcodes. Values below 16 are transport records.\npub mod op {\n");
    for cmd in &api.commands {
        writeln!(out, "    pub const {}: u32 = {};", cmd.name, cmd.opcode).ok();
    }
    writeln!(out, "    /// One past the highest opcode.\n    pub const END: u32 = {};", api.commands.last().map_or(16, |c| c.opcode + 1)).ok();
    out.push_str("}\n\n");

    out.push_str("/// The fixed part of each record, after its header. Pointers are\n/// signed offsets from the record start (0 is null); handles are ids.\npub mod frame {\n    use super::vk::*;\n\n");
    for cmd in &api.commands {
        writeln!(out, "    #[repr(C, align(8))]\n    pub struct {} {{", cmd.name).ok();
        for p in &cmd.params {
            if let Some(ty) = frame_type(api, &p.kind, &p.member) {
                writeln!(out, "        pub {}: {ty},", ident(&p.member.name)).ok();
            }
        }
        if cmd.sync {
            out.push_str("        /// Offset of the reply block: the return value, then outputs.\n        pub reply: i64,\n");
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");

    // How a reply is laid out is part of the protocol too.
    let arrays = api.output_arrays();
    out.push_str("\n/// Output structures whose array follows them in a reply.\n");
    writeln!(out, "pub const OUTPUT_ARRAYS: [&str; {}] = [", arrays.len()).ok();
    for (name, ..) in &arrays {
        writeln!(out, "    \"{name}\",").ok();
    }
    out.push_str("];\n");

    let hash = out.bytes().fold(0xcbf2_9ce4_8422_2325_u64, |hash, byte| {
        (hash ^ u64::from(byte)).wrapping_mul(0x0100_0000_01b3)
    });
    writeln!(out, "\n/// Both ends must be generated from the same inputs.\npub const PROTOCOL: u64 = 0x{hash:016x};").ok();
    out
}
